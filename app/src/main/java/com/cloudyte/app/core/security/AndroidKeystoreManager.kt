package com.cloudyte.app.core.security

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import java.security.SecureRandom
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.SecretKeySpec

data class MasterKeyWrappedPayload(
    val nonce: ByteArray,
    val ciphertextWithTag: ByteArray
) {
    override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (other !is MasterKeyWrappedPayload) return false
        return nonce.contentEquals(other.nonce) && ciphertextWithTag.contentEquals(other.ciphertextWithTag)
    }

    override fun hashCode(): Int {
        var result = nonce.contentHashCode()
        result = 31 * result + ciphertextWithTag.contentHashCode()
        return result
    }
}

interface MasterKeyWrapper {
    @Throws(CryptoException::class)
    fun wrap(plaintextKey: ByteArray, aad: ByteArray? = null): MasterKeyWrappedPayload

    @Throws(CryptoException::class)
    fun unwrap(nonce: ByteArray, ciphertextWithTag: ByteArray, aad: ByteArray? = null): ByteArray

    fun isMasterKeyAvailable(): Boolean
}

/**
 * Production Android Keystore master key manager using alias `cloudyte_master_key_v1`,
 * AES-256-GCM, NoPadding, PURPOSE_ENCRYPT | PURPOSE_DECRYPT.
 */
class AndroidKeystoreManager(
    private val keyAlias: String = CryptoConstants.MASTER_KEY_ALIAS,
    private val keyStoreProvider: String = CryptoConstants.KEYSTORE_PROVIDER
) : MasterKeyWrapper {

    @Synchronized
    override fun wrap(plaintextKey: ByteArray, aad: ByteArray?): MasterKeyWrappedPayload {
        return try {
            val masterKey = getOrCreateMasterKey()
            val cipher = Cipher.getInstance(CryptoConstants.AES_GCM_TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, masterKey)
            if (aad != null && aad.isNotEmpty()) {
                cipher.updateAAD(aad)
            }
            val ciphertext = cipher.doFinal(plaintextKey)
            val iv = cipher.iv
            if (iv == null || iv.size != CryptoConstants.GCM_NONCE_LENGTH_BYTES) {
                throw KeyUnwrapException("Invalid IV length generated by Keystore GCM cipher")
            }
            MasterKeyWrappedPayload(nonce = iv, ciphertextWithTag = ciphertext)
        } catch (e: CryptoException) {
            throw e
        } catch (e: Exception) {
            throw KeyUnavailableException("Android Keystore failed to wrap content key", e)
        }
    }

    @Synchronized
    override fun unwrap(nonce: ByteArray, ciphertextWithTag: ByteArray, aad: ByteArray?): ByteArray {
        if (nonce.size != CryptoConstants.GCM_NONCE_LENGTH_BYTES) {
            throw KeyUnwrapException("Invalid wrapped key nonce length: ${nonce.size}")
        }
        return try {
            val masterKey = getExistingMasterKey()
                ?: throw KeyUnavailableException("Android Keystore master key '$keyAlias' does not exist")
            val cipher = Cipher.getInstance(CryptoConstants.AES_GCM_TRANSFORMATION)
            val spec = GCMParameterSpec(CryptoConstants.GCM_TAG_LENGTH_BITS, nonce)
            cipher.init(Cipher.DECRYPT_MODE, masterKey, spec)
            if (aad != null && aad.isNotEmpty()) {
                cipher.updateAAD(aad)
            }
            cipher.doFinal(ciphertextWithTag)
        } catch (e: CryptoException) {
            throw e
        } catch (e: Exception) {
            throw KeyUnwrapException("Failed to unwrap content key using Android Keystore master key", e)
        }
    }

    @Synchronized
    override fun isMasterKeyAvailable(): Boolean {
        return try {
            val ks = KeyStore.getInstance(keyStoreProvider)
            ks.load(null)
            ks.containsAlias(keyAlias)
        } catch (_: Exception) {
            false
        }
    }

    @Synchronized
    private fun getExistingMasterKey(): SecretKey? {
        val ks = KeyStore.getInstance(keyStoreProvider)
        ks.load(null)
        val entry = ks.getEntry(keyAlias, null) as? KeyStore.SecretKeyEntry
        return entry?.secretKey
    }

    @Synchronized
    private fun getOrCreateMasterKey(): SecretKey {
        getExistingMasterKey()?.let { return it }

        val keyGenerator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,
            keyStoreProvider
        )
        val spec = KeyGenParameterSpec.Builder(
            keyAlias,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(CryptoConstants.AES_KEY_SIZE_BITS)
            .setRandomizedEncryptionRequired(true)
            .build()

        keyGenerator.init(spec)
        return keyGenerator.generateKey()
    }
}

/**
 * Software-backed MasterKeyWrapper for deterministic JVM unit tests where AndroidKeyStore hardware
 * provider is not present. Uses AES-256-GCM with SecureRandom 12-byte nonces and 128-bit tags.
 */
class JvmMemoryMasterKeyWrapper(
    initialMasterKeyBytes: ByteArray? = null,
    private val secureRandom: SecureRandom = SecureRandom()
) : MasterKeyWrapper {
    @Volatile
    private var masterKeyBytes: ByteArray? = initialMasterKeyBytes?.copyOf()

    @Volatile
    var forceFailure: Boolean = false

    fun clearMasterKey() {
        masterKeyBytes?.fill(0)
        masterKeyBytes = null
    }

    fun rotateMasterKey() {
        val next = ByteArray(CryptoConstants.AES_KEY_SIZE_BYTES)
        secureRandom.nextBytes(next)
        masterKeyBytes = next
    }

    override fun wrap(plaintextKey: ByteArray, aad: ByteArray?): MasterKeyWrappedPayload {
        if (forceFailure) {
            throw KeyUnavailableException("Simulated Keystore failure during wrap")
        }
        val keyBytes = masterKeyBytes ?: ByteArray(CryptoConstants.AES_KEY_SIZE_BYTES).also {
            secureRandom.nextBytes(it)
            masterKeyBytes = it
        }
        val nonce = ByteArray(CryptoConstants.GCM_NONCE_LENGTH_BYTES)
        secureRandom.nextBytes(nonce)
        val cipher = Cipher.getInstance(CryptoConstants.AES_GCM_TRANSFORMATION)
        cipher.init(
            Cipher.ENCRYPT_MODE,
            SecretKeySpec(keyBytes, CryptoConstants.AES_ALGORITHM),
            GCMParameterSpec(CryptoConstants.GCM_TAG_LENGTH_BITS, nonce)
        )
        if (aad != null && aad.isNotEmpty()) {
            cipher.updateAAD(aad)
        }
        val ciphertext = cipher.doFinal(plaintextKey)
        return MasterKeyWrappedPayload(nonce = nonce, ciphertextWithTag = ciphertext)
    }

    override fun unwrap(nonce: ByteArray, ciphertextWithTag: ByteArray, aad: ByteArray?): ByteArray {
        if (forceFailure) {
            throw KeyUnwrapException("Simulated Keystore failure during unwrap")
        }
        val keyBytes = masterKeyBytes
            ?: throw KeyUnavailableException("Master key is missing in JvmMemoryMasterKeyWrapper")
        return try {
            val cipher = Cipher.getInstance(CryptoConstants.AES_GCM_TRANSFORMATION)
            cipher.init(
                Cipher.DECRYPT_MODE,
                SecretKeySpec(keyBytes, CryptoConstants.AES_ALGORITHM),
                GCMParameterSpec(CryptoConstants.GCM_TAG_LENGTH_BITS, nonce)
            )
            if (aad != null && aad.isNotEmpty()) {
                cipher.updateAAD(aad)
            }
            cipher.doFinal(ciphertextWithTag)
        } catch (e: Exception) {
            throw KeyUnwrapException("Failed to unwrap content key with master key", e)
        }
    }

    override fun isMasterKeyAvailable(): Boolean = !forceFailure && masterKeyBytes != null
}
